"""Assemble the manuscript: Markdown parts + numbers computed from result files -> DOCX (pandoc, native
Word equations, Elsevier numeric references via CSL) -> PDF (LibreOffice).

Usage: python build_manuscript.py [--allow-missing]
Every {{key}} placeholder is replaced by a value from values.json (generated by compute_values.py from the
machine-readable results). The build fails if a placeholder has no value (unless --allow-missing).
"""
import json, os, re, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(HERE, "..", "src")

def main():
    allow = "--allow-missing" in sys.argv
    parts = sorted(f for f in os.listdir(SRC) if f.startswith("part") and f.endswith(".md"))
    text = "\n\n".join(open(os.path.join(SRC, f), encoding="utf-8").read() for f in parts)
    vals_path = os.path.join(HERE, "values.json")
    vals = json.load(open(vals_path)) if os.path.exists(vals_path) else {}
    missing = sorted(set(re.findall(r"\{\{(\w+)\}\}", text)) - set(vals))
    if missing and not allow:
        sys.exit(f"Missing values for placeholders: {missing}")
    text = re.sub(r"\{\{(\w+)\}\}", lambda m: str(vals.get(m.group(1), f"[[{m.group(1)}]]")), text)
    # number table captions in order of appearance
    k = [0]
    def _num(m):
        k[0] += 1
        return f"Table: **Table {k[0]}.** "
    text = re.sub(r"^Table: ", _num, text, flags=re.M)
    # loose lists: blank line before every list item (renders lists in body style, not the table "Compact" style)
    lines, outl = text.split("\n"), []
    for ln in lines:
        if re.match(r"^(\s*)(- |\d+\. )", ln) and outl and outl[-1].strip() != "":
            outl.append("")
        outl.append(ln)
    text = "\n".join(outl)
    # figures are referenced relative to the submission root
    md = os.path.join(HERE, "manuscript_filled.md")
    open(md, "w", encoding="utf-8").write(text)
    out_docx = os.path.join(ROOT, "manuscript", "Final_Manuscript.docx")
    subprocess.run(["pandoc", md, "-o", out_docx, "--citeproc", "--bibliography", os.path.join(HERE, "references.json"),
                    "--csl", os.path.join(HERE, "elsevier-with-titles.csl"), "--reference-doc", os.path.join(HERE, "reference.docx"),
                    "--resource-path", ROOT, "-M", "link-citations=false", "-M", "reference-section-title=References"],
                   check=True, cwd=ROOT)
    from postprocess_docx import postprocess
    postprocess(out_docx)
    subprocess.run(["soffice", "--headless", "--convert-to", "pdf", "--outdir", os.path.dirname(out_docx), out_docx],
                   check=True, capture_output=True)
    print("built", out_docx)
    # cover letter (same placeholder mechanism)
    cl = open(os.path.join(HERE, "..", "src_cover", "cover_letter.md"), encoding="utf-8").read()
    cl = re.sub(r"\{\{(\w+)\}\}", lambda m: str(vals.get(m.group(1), f"[[{m.group(1)}]]")), cl)
    cl_lines, cl_out = cl.split("\n"), []
    for ln in cl_lines:
        if re.match(r"^(\s*)(- |\d+\. )", ln) and cl_out and cl_out[-1].strip() != "":
            cl_out.append("")
        cl_out.append(ln)
    cl = "\n".join(cl_out)
    clmd = os.path.join(HERE, "cover_letter_filled.md"); open(clmd, "w", encoding="utf-8").write(cl)
    cl_docx = os.path.join(ROOT, "manuscript", "cover_letter.docx")
    subprocess.run(["pandoc", clmd, "-o", cl_docx, "--reference-doc", os.path.join(HERE, "reference_letter.docx")], check=True)
    subprocess.run(["soffice", "--headless", "--convert-to", "pdf", "--outdir", os.path.dirname(cl_docx), cl_docx], check=True, capture_output=True)
    # review records: fill numeric placeholders from the same values (rendered copies)
    rdir = os.path.join(ROOT, "REVIEW")
    for f in sorted(os.listdir(rdir)):
        if f.endswith(".md"):
            t = open(os.path.join(rdir, f), encoding="utf-8").read()
            if "{{" in t:
                t = re.sub(r"\{\{(\w+)\}\}", lambda m: str(vals.get(m.group(1), f"[[{m.group(1)}]]")), t)
                open(os.path.join(rdir, f), "w", encoding="utf-8").write(t)
    print("built cover letter and filled review records")
    # figure files renamed by their manuscript number (for upload)
    import shutil
    SUBMISSION_FIGS = {"Fig1": "fig1_workflow", "Fig2": "fig2_datasets", "Fig3": "fig3_coverage_vs_m", "Fig4": "fig4_width_vs_m",
                       "Fig5": "fig5_ablation", "Fig6": "fig7_conditional_coverage", "Fig7": "fig6_robustness",
                       "Fig8": "fig8_error_analysis", "Fig9": "fig10_coverage_distribution", "FigS1": "figS1_cnn_training",
                       "FigS2": "figS2_friedman_ranks", "FigS3": "fig9_timing", "GraphicalAbstract": "graphical_abstract"}
    sub = os.path.join(ROOT, "figures", "submission"); os.makedirs(sub, exist_ok=True)
    for new, old in SUBMISSION_FIGS.items():
        for ext in (".png", ".pdf"):
            shutil.copyfile(os.path.join(ROOT, "figures", old + ext), os.path.join(sub, new + ext))
    # check the mapping against the manuscript itself
    for new, old in SUBMISSION_FIGS.items():
        if new.startswith("Fig") and not new.startswith("FigS"):
            n = new[3:]
            assert re.search(r"\*\*Fig\. " + n + r"\.\*\*[^\n]*\]\(figures/" + old + r"\.png\)", text), (new, old)
    print("submission figure set written and verified")

if __name__ == "__main__":
    main()
